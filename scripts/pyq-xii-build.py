#!/usr/bin/env python3
"""
Builds the Class 12 Mathematics board history from the tagged papers.

  python3 scripts/pyq-xii-build.py

Reads docs/content/tagged-history-xii/<folder>/<paper>.json, checks every row
against the chapters and topics in prisma/seeding/curriculum-xii.data.ts, and writes:
  docs/content/board-history-xii.json       all rows (loaded by npm run db:seed:class12)
  docs/content/class12-board-coverage.md    what the board asks, chapter by chapter
Exits non-zero if a row has an unknown chapter or topic.
"""
import collections, glob, json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
CONTENT = os.path.join(ROOT, 'docs/content')
src = open(os.path.join(ROOT, 'prisma/seeding/curriculum-xii.data.ts')).read()


def parse(block_name):
    block = src.split(f'export const {block_name}')[1].split('\n};')[0]
    out = {}
    for m in re.finditer(r"'([^']+)':\s*\[(.*?)\]", block, re.S):
        out[m.group(1)] = re.findall(r"'((?:[^'\\]|\\.)*)'|\"([^\"]*)\"", m.group(2))
        out[m.group(1)] = [a.replace("\\'", "'") or b for a, b in out[m.group(1)]]
    return out


CURRENT, LEGACY = parse('TOPICS_XII'), parse('LEGACY_TOPICS_XII')
CHAPTERS = list(CURRENT)

rows, problems = [], []
for f in sorted(glob.glob(os.path.join(CONTENT, 'tagged-history-xii', '*', '*.json'))):
    folder = os.path.basename(os.path.dirname(f))
    for r in json.load(open(f)):
        r.setdefault('exam', 'compartment' if 'COMPTT' in folder else 'main')
        r.setdefault('year', int(folder[:4]))
        where = f"{folder}/{os.path.basename(f)} Q{r.get('qno')}"
        if r.get('chapter') not in CURRENT:
            problems.append(f'{where}: unknown chapter "{r.get("chapter")}"'); continue
        t = r.get('topic', '')
        if t in LEGACY.get(r['chapter'], []):
            r['legacySyllabus'] = True
        elif t not in CURRENT[r['chapter']] and not t.startswith('NEW:'):
            problems.append(f'{where}: topic "{t}" is not under {r["chapter"]}')
        if not r.get('paperId'):
            problems.append(f'{where}: no paperId')
        rows.append(r)

keys = collections.Counter((r.get('paperId'), str(r.get('qno'))) for r in rows)
problems += [f'duplicate row {k}' for k, n in keys.items() if n > 1]

json.dump(rows, open(os.path.join(CONTENT, 'board-history-xii.json'), 'w'), indent=1, ensure_ascii=False)

# Coverage report
papers = collections.defaultdict(set)
for r in rows: papers[(r['year'], r['exam'])].add(r['paperId'])
recent = [r for r in rows if r['year'] >= 2023 and r['exam'] == 'main']
n_recent = len({r['paperId'] for r in recent}) or 1
L = ['# Class 12 Mathematics: what the board asks', '',
     'Generated by `scripts/pyq-xii-build.py` from the tagged papers in `docs/content/tagged-history-xii/`; do not edit by hand.', '',
     f'{len(rows)} questions from {len({r["paperId"] for r in rows})} papers, {min(r["year"] for r in rows)}–{max(r["year"] for r in rows)}. '
     f'{sum(1 for r in rows if r.get("legacySyllabus"))} need a topic CBSE has since cut.', '',
     '## Papers by year', '', '| Year | Exam | Papers | Questions |', '|---|---|---|---|']
for (y, e), ps in sorted(papers.items()):
    L.append(f'| {y} | {e} | {len(ps)} | {sum(1 for r in rows if r["year"] == y and r["exam"] == e)} |')
L += ['', '## Chapter weight in the current format (2023 onwards, main exam)', '',
      f'Average marks per paper, across {n_recent} papers.', '', '| Chapter | Marks per paper | Questions per paper | Last asked |', '|---|---|---|---|']
for ch in CHAPTERS:
    rs = [r for r in recent if r['chapter'] == ch]
    last = max((r['year'] for r in rows if r['chapter'] == ch), default='never')
    L.append(f'| {ch} | {sum(r.get("marks", 0) for r in rs) / n_recent:.1f} | {len(rs) / n_recent:.1f} | {last} |')
L += ['', '## Topics', '']
for ch in CHAPTERS:
    L += [f'### {ch}', '', '| Topic | Times asked | 2023 onwards | Last asked |', '|---|---|---|---|']
    names = CURRENT[ch] + [f'{t} *(cut)*' for t in LEGACY.get(ch, [])]
    for name in names:
        t = name.replace(' *(cut)*', '')
        rs = [r for r in rows if r['chapter'] == ch and r.get('topic') == t]
        L.append(f'| {name} | {len(rs)} | {sum(1 for r in rs if r["year"] >= 2023)} | {max((r["year"] for r in rs), default="never")} |')
    new = collections.Counter(r['topic'] for r in rows if r['chapter'] == ch and r.get('topic', '').startswith('NEW:'))
    for t, n in new.most_common():
        L.append(f'| {t} | {n} | | |')
    L.append('')
if problems:
    L += ['## Problems found', ''] + [f'- {p}' for p in problems[:200]]
open(os.path.join(CONTENT, 'class12-board-coverage.md'), 'w').write('\n'.join(L) + '\n')

print(f'{len(rows)} rows from {len({r["paperId"] for r in rows})} papers; {len(problems)} problems')
for p in problems[:40]: print('  ', p)
sys.exit(1 if any('unknown chapter' in p or 'is not under' in p for p in problems) else 0)
